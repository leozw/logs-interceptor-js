const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { spawnSync, execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const source = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
const directory = path.join(root, 'release', '3.0.0', source);
const receipt = JSON.parse(fs.readFileSync(path.join(directory, 'receipt.json')));
const archive = path.join(directory, receipt.filename);
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(receipt.name, 'logs-interceptor');
assert.equal(receipt.version, '3.0.0');
assert.equal(receipt.source, source);
assert.equal(sha(fs.readFileSync(archive)), receipt.sha256);
fs.mkdirSync(path.join(root, '.rebuild'), { recursive: true });
const consumer = fs.mkdtempSync(path.join(root, '.rebuild/packed-consumer-'));
const home = path.join(consumer, 'home');
fs.mkdirSync(home);
fs.writeFileSync(path.join(consumer, 'package.json'), JSON.stringify({ name: 'legacy-major-packed-review', private: true }));
const env = { PATH: path.dirname(process.execPath) + ':/usr/bin:/bin', HOME: home };
const cli = process.argv[2];
const winstonVersion = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'))).packages['node_modules/winston'].version;
const args = ['install', '--ignore-scripts', '--no-audit', '--no-fund', '--save-exact', '--userconfig=/dev/null', '--globalconfig=' + path.join(home, 'global.npmrc'), '--cache=' + path.join(consumer, 'cache'), '--registry=https://registry.npmjs.org/', archive, 'winston@' + winstonVersion];
const installed = spawnSync(cli ? process.execPath : 'npm', cli ? [cli, ...args] : args, { cwd: consumer, env, encoding: 'utf8', timeout: 120000, maxBuffer: 4 * 1024 * 1024 });
fs.writeFileSync(path.join(consumer, 'install.log'), installed.stdout + installed.stderr);
assert.equal(installed.status, 0, 'Fresh public-dependency consumer install failed; see ' + consumer);
const pkg = path.join(consumer, 'node_modules/logs-interceptor');
const files = execFileSync('tar', ['-tzf', archive], { encoding: 'utf8' }).trim().split('\n').filter(file => !file.endsWith('/'));
for (const file of files) {
  assert.ok(file.startsWith('package/') && !file.includes('../'));
  const bytes = execFileSync('tar', ['-xOf', archive, file], { maxBuffer: 2 * 1024 * 1024 });
  assert.equal(sha(fs.readFileSync(path.join(pkg, file.slice(8)))), sha(bytes), 'Installed file identity mismatch: ' + file);
}
fs.symlinkSync('node_modules/logs-interceptor/dist', path.join(consumer, 'dist'));
fs.symlinkSync('node_modules/logs-interceptor/preload.js', path.join(consumer, 'preload.js'));
fs.mkdirSync(path.join(consumer, 'tests'));
const testFiles = fs.readdirSync(path.join(root, 'tests')).filter(file => file.endsWith('.test.cjs')).sort();
for (const file of testFiles) fs.copyFileSync(path.join(root, 'tests', file), path.join(consumer, 'tests', file));
fs.copyFileSync(path.join(root, 'tests/assert-jest-parity.cjs'), path.join(consumer, 'tests/assert-jest-parity.cjs'));
fs.copyFileSync(path.join(root, 'tests/typescript-contract.ts'), path.join(consumer, 'tests/typescript-contract.ts'));
const typed = spawnSync(process.execPath, [path.join(root, 'node_modules/typescript/bin/tsc'), '--strict', '--skipLibCheck', '--noEmit', '--module', 'NodeNext', '--moduleResolution', 'NodeNext', '--target', 'ES2020', '--typeRoots', path.join(root, 'node_modules/@types'), path.join(consumer, 'tests/typescript-contract.ts')], { cwd: consumer, env, encoding: 'utf8', timeout: 30000, maxBuffer: 2 * 1024 * 1024 });
fs.writeFileSync(path.join(consumer, 'types.log'), typed.stdout + typed.stderr);
assert.equal(typed.status, 0, 'Strict installed declaration contract failed; see ' + consumer);
const tested = spawnSync(process.execPath, ['--test', '--test-reporter=tap', ...testFiles.map(file => path.join(consumer, 'tests', file))], { cwd: consumer, env, encoding: 'utf8', timeout: 60000, maxBuffer: 8 * 1024 * 1024 });
const testLog = 'packed-tests-' + process.versions.node + '.log';
fs.writeFileSync(path.join(directory, testLog), tested.stdout + tested.stderr);
const tests = Number(tested.stdout.match(/# tests (\d+)/)?.[1]);
const output = { capturedAt: new Date().toISOString(), source: receipt.source, name: receipt.name, version: receipt.version, archiveSha256: receipt.sha256, node: process.version, platform: process.platform, arch: process.arch, consumer, freshInstall: true, credentialEnvironmentForwarded: false, installedFilesByteMatched: files.length, strictInstalledDeclarationContract: typed.status === 0, tests, status: tested.status, log: testLog, publication: 'NOT_AUTHORIZED; fresh independent review, ownership and provenance gates remain' };
fs.writeFileSync(path.join(directory, 'packed-consumer-' + process.versions.node + '.json'), JSON.stringify(output, null, 2) + '\n');
console.log(JSON.stringify(output));
assert.equal(tested.status, 0);
assert.equal(tests, 61);
